"""
Provides the "Augment : Twister" component, which builds a twist setup between
a root and tip driver and parent constrains each given joint to a twist
transform blended by its distance along the chain.
"""
import os
import aniseed
import aniseed_toolkit
from aniseed_maya_standard.mixins import MirrorMixin


class TwisterComponent(aniseed.RigComponent, MirrorMixin):
    """
    Builds a twist setup along a chain of joints driven by a Root and
    Tip driver. The augment creates a twist rig (via
    ``aniseed_toolkit.rigging.twist.create_twist_driver``), aligns its org to the root
    driver and its tip to the tip driver, optionally parent-constrains
    those ends to the drivers, and then distributes the supplied joints
    along the twist by their normalised distance from root to tip.

    Each driven joint is parent-constrained to its matching twist
    transform, so the joints inherit the blended twist rotation between
    the two drivers.
    """

    identifier = "Augment : Twister"
    icon = os.path.join(
        os.path.dirname(__file__),
        "twister.png",
    )

    def __init__(self, *args, **kwargs):
        """
        Declares the "Parent", "Joints", "Root" and "Tip" inputs, the naming
        and constraint options and the "Twisters" output. The twist builder
        from the last run is kept on self.builder.
        """
        super().__init__(*args, **kwargs)

        self.builder = None

        self.declare_input(
            name="Parent",
            description="The node the twist rig's org will be parented under",
            validate=True,
            group="Control Rig",
        )

        self.declare_input(
            name="Joints",
            description=(
                "The joints to be driven by the twist setup. Each joint is "
                "parent-constrained to a twist transform whose blend factor "
                "is set by the joint's normalised distance from Root to Tip."
            ),
            validate=True,
            group="Required Joints",
        )

        self.declare_input(
            name="Root",
            description=(
                "The driver that defines the root of the twist. The twist "
                "org is matched to this node's world matrix, and (if "
                "``Constrain Root`` is enabled) the twist root is "
                "parent-constrained to it."
            ),
            validate=True,
            group="Required Joints",
        )

        self.declare_input(
            name="Tip",
            description=(
                "The driver that defines the tip of the twist. The twist "
                "tip is translated to this node's world position, and (if "
                "``Constrain Tip`` is enabled) the twist tip is "
                "parent-constrained to it."
            ),
            validate=True,
            group="Required Joints",
        )

        self.declare_option(
            name="Descriptive Prefix",
            description="Prefix used when naming the nodes generated by the twist setup",
            value="",
            group="Naming",
        )

        self.declare_option(
            name="Location",
            description="Location token (e.g. md/lf/rt) applied to generated node names",
            value=self.config.middle,
            group="Naming",
            should_inherit=True,
            pre_expose=True,
        )

        self.declare_option(
            name="Constrain Root",
            description=(
                "If enabled, parent-constrains the twist root to the Root "
                "driver with maintainOffset so the root follows that driver."
            ),
            value=True,
            group="Behaviour",
        )

        self.declare_option(
            name="Constrain Tip",
            description=(
                "If enabled, parent-constrains the twist tip to the Tip "
                "driver with maintainOffset so the tip follows that driver."
            ),
            value=True,
            group="Behaviour",
        )

        self.declare_output(
            name="Twisters",
            description="The list of twist transforms produced by the setup, one per driven joint",
        )

    def option_widget(self, option_name):
        """
        Returns a location selector for the "Location" option.

        Args:
            option_name: The name of the option to return a widget for.
        """

        if option_name == "Location":
            return aniseed.widgets.LocationSelector(
                config=self.config,
            )

    def input_widget(self, requirement_name):
        """
        Returns an object list for the "Joints" input and object selectors for
        the "Root" and "Tip" inputs.

        Args:
            requirement_name: The name of the input to return a widget for.
        """
        if requirement_name == "Joints":
            return aniseed.widgets.ObjectList()

        if requirement_name == "Root":
            return aniseed.widgets.ObjectSelector(component=self)

        if requirement_name == "Tip":
            return aniseed.widgets.ObjectSelector(component=self)

    def is_valid(self) -> bool:
        """
        Checks that joints have been given and that the chain from the first to
        the last joint has a known facing direction.
        """

        joints = self.input("Joints").get()

        if not joints:
            print("No joints given to drive")
            return False

        facing_direction = aniseed_toolkit.scene.joints.get_chain_facing_direction(
            start=joints[0],
            end=joints[-1],
        )
        if facing_direction == facing_direction.Unknown:
            print("Not a valid facing direction")
            return False

        return True

    def run(self):
        """
        Creates a twist setup with one twist per joint, places its org at the
        root driver and its tip at the tip driver, and optionally constrains the
        root and tip to their drivers. Each twist's blend factor is set from its
        joint's distance from the root driver relative to the root to tip
        distance, and the joint is parent constrained to the twist. The twists
        are written to the "Twisters" output.
        """

        twist_builder = aniseed_toolkit.rigging.twist.create_twist_driver(
            joints=self.input("Joints").get(),
            parent=self.input("Parent").get(),
            root=self.input("Root").get(),
            tip=self.input("Tip").get(),
            description=self.option("Descriptive Prefix").get(),
            location=self.option("Location").get(),
            config=self.config,
            constrain_root=self.option("Constrain Root").get(),
            constrain_tip=self.option("Constrain Tip").get(),
        )

        self.builder = twist_builder

        self.output("Twisters").set(
            twist_builder.twists(),
        )

        return True
