"""
Provides the "Mechanics : Two Bone IKFK" component, a generic ik/fk rig for a
three joint chain such as an arm or leg. It uses the toolkit's two bone ik/fk
setup with fk, ik target, upvector and config controls, an ikfk blend attribute,
optional soft ik and fk world space switches, and ik/fk snapping.
"""
import os
import mref
import snappy
import aniseed
import aniseed_toolkit


# noinspection PyInterpreter
class SimpleIKFKComponent(aniseed.RigComponent, aniseed.mixins.MirrorMixin):
    """
    Builds a two-bone IK/FK rig for a three-joint chain (e.g. an arm
    or leg). Creates an FK chain (upper / lower / end controls), an IK
    target control, a pole-vector control, and a config control that
    hosts the ``ikfk`` blend attribute. The toolkit's two-bone IK/FK
    setup is used internally, then constrained to the FK and IK
    controls and wired to a visibility switch driven off the blend
    attribute. Optional behaviours include soft IK, world-aligned IK /
    upvector controls, and world-space space switches on the FK
    controls.

    The three "Blended" outputs expose the blend-chain joints
    downstream components hook onto for skinning.
    """

    identifier = "Mechanics : Two Bone IKFK"
    icon = os.path.join(
        os.path.dirname(__file__),
        "arm.png",
    )

    # noinspection PyUnresolvedReferences
    def __init__(self, *args, **kwargs):
        """
        Declares the parent and root/tip joint inputs, the naming and ik/fk
        behaviour options (ik control override, world alignment, soft ik, fk
        world switches, config placement) and the three blended joint outputs.
        """
        super().__init__(*args, **kwargs)

        self.declare_input(
            name="Parent",
            description="The parent for the control hierarchy",
            validate=True,
            group="Control Rig",
        )

        self.declare_input(
            name="Root Joint",
            description="The root of the chain",
            validate=True,
            group="Required Joints"
        )

        self.declare_input(
            name="Tip Joint",
            description="The tip of the chain",
            validate=True,
            group="Required Joints"
        )

        self.declare_option(
            name="Descriptive Prefix",
            description="Prefix used when naming the controls, mechanical nodes, and snap group generated by the rig",
            value="",
            group="Naming",
            pre_expose=True,
        )

        self.declare_option(
            name="Location",
            description="Location token (e.g. md/lf/rt) applied to generated node names",
            value=self.config.left,
            group="Naming",
            pre_expose=True,
        )

        self.declare_option(
            name="IK Control Transform",
            description=(
                "An optional transform to override the transform of the ik control"
            ),
            value="",
            group="Behaviour",
        )
        self.declare_option(
            name="Align IK To World",
            description=(
                "If enabled, the IK target control's org is rotated to "
                "world orientation after creation, so the IK control's "
                "rotation gizmo lines up with world axes instead of the "
                "tip joint's axes."
            ),
            value=False,
            group="Behaviour",
        )

        self.declare_option(
            name="Align Upvector To World",
            description=(
                "If enabled, the upvector control's org is rotated to "
                "world orientation after being positioned at the computed "
                "upvector point, so the control's rotation gizmo lines up "
                "with world axes."
            ),
            value=True,
            group="Behaviour",
        )

        self.declare_option(
            name="Apply Soft Ik",
            description=(
                "If enabled, soft IK is applied to the IK chain so the "
                "end of the chain eases towards the IK target rather "
                "than snapping fully extended at the limit."
            ),
            value=True,
            group="Behaviour",
        )

        self.declare_option(
            name="Apply World Fk Switches",
            description=(
                "If enabled, each FK control gets a world-space space "
                "switch added (via the toolkit's "
                "``setup_fk_worldspace_switches``), letting animators "
                "switch FK controls between local and world parenting."
            ),
            value=True,
            group="Behaviour",
        )

        self.declare_option(
            name="Make Config Child Of End",
            description="",
            value=False,
            group="Behaviour",
        )

        self.declare_option(
            name="Constrain End Point Rotation",
            description="",
            value=True,
            group="Behaviour",
        )

        self.declare_output(
            name="Blended Upper",
            description="The upper joint of the IK/FK blend chain (drives the upper skin joint downstream)",
        )

        self.declare_output(
            name="Blended Lower",
            description="The lower joint of the IK/FK blend chain (drives the lower skin joint downstream)",
        )

        self.declare_output(
            name="Blended Tip",
            description="The tip joint of the IK/FK blend chain (drives the tip skin joint downstream)",
        )

        # -- The build is broken up into functions, so these properties hold
        # -- the items which are shared between them
        self._clear_values()

    def _clear_values(self):
        """
        Resets the properties shared between the build functions to their
        empty defaults.
        """
        self.prefix: str = ""
        self.location: str = ""
        self.org: str = ""
        self.joints: list[str] = []
        self.config_control: "Control" = None
        self.upvector_control: "Control" = None
        self.ik_target_control: "Control" = None
        self.fk_upper_control: "Control" = None
        self.fk_lower_control: "Control" = None
        self.fk_end_control: "Control" = None

        self.fk_controls: list[str] = []
        self.ik_controls: list[str] = []
        self.nk_joints: list[str] = []
        self.shape_rotation = [90, 0, 0]

    def on_enter_stack(self):
        """
        Hooks the Parent input to the parent component's default output.
        """
        # -- Attempt to auto resolve the parent based on its default output
        self.input("Parent").hook_to_parent()

    def option_widget(self, option_name: str):
        """
        This allows us to provide dedicate widgets for specific options
        """
        if option_name == "Location":
            return aniseed.widgets.LocationSelector(self.config, self.option(option_name).get())

        if option_name == "IK Control Transform":
            return aniseed.widgets.ObjectSelector()

    def input_widget(self, requirement_name):
        """
        This allows us to provide dedicate widgets for specific inputs
        """
        if requirement_name in ["Parent", "Root Joint", "Tip Joint"]:
            return aniseed.widgets.ObjectSelector(component=self)

    def is_valid(self):
        """
        Checks that the chain between the root and tip joints faces down the
        positive or negative X axis.
        """

        limb_joints = aniseed_toolkit.scene.joints.get_between(
            start=self.input("Root Joint").get(),
            end=self.input("Tip Joint").get(),
        )

        direction = aniseed_toolkit.scene.joints.get_chain_facing_direction(
            start=limb_joints[0],
            end=limb_joints[-1],
        )

        if direction != direction.PositiveX and direction != direction.NegativeX:
            print("Validation Warning : Chain is not failing Up/Down X")
            print(f"    Tested Chain : {limb_joints}")
            print(direction)
            return False

        return True

    def run(self):
        """
        This is triggered when the stack is executed
        """
        self._clear_values()
        self.prefix = self.option('Descriptive Prefix').get()
        self.location = self.option("Location").get()

        self.org = aniseed_toolkit.scene.transforms.create(
            classification=self.config.organisational,
            description=f"{self.prefix}Arm",
            location=self.location,
            config=self.config,
            parent=self.input("Parent").get(),
            match_to=self.input("Parent").get()
        )
        self.joints = aniseed_toolkit.scene.joints.get_between(
            start=self.input('Root Joint').get(),
            end=self.input("Tip Joint").get(),
        )
        self._create_controls()

        ikfk_setup = aniseed_toolkit.rigging.create_two_bone_ikfk(
            parent=self.org,
            root_joint=self.joints[0],
            end_joint=self.joints[-1],
            attribute_host=self.config_control.ctl,
            attribute_name="ikfk",
            constrain=True,
            soft_ik=self.option("Apply Soft Ik").get(),
            soft_ik_host=self.ik_target_control.ctl,
            constrain_endpoint_rotation=self.option("Constrain End Point Rotation").get(),
            ik_target_transform_override=self.option("IK Control Transform").get(),
        )

        if self.option("Make Config Child Of End").get():
            config_org = mref.get(self.config_control.org)
            config_org.set_parent(ikfk_setup.blend_chain[-1])
            config_org.match_to(ikfk_setup.blend_chain[-1])

        # -- Create the guide line
        aniseed_toolkit.rig.guide.link(
            self.upvector_control.ctl,
            ikfk_setup.ik_chain[1].name(),
        )

        for node in ikfk_setup.all_nodes():
            node.rename(
                self.config.generate_name(
                    classification="mech",
                    description=f"{self.prefix}{node.name()}",
                    location=self.location,
                ),
            )

        mref.parentConstraint(
            self.ik_target_control.ctl,
            ikfk_setup.ik_target,
            maintainOffset=True,
        )
        mref.parentConstraint(
            self.upvector_control.ctl,
            ikfk_setup.ik_upvector,
            maintainOffset=False,
        )

        for fk_control, fk_marker in zip(self.fk_controls, ikfk_setup.fk_chain):
            mref.parentConstraint(
                fk_control,
                fk_marker,
                maintainOffset=True,
            )

        # -- Hook up the visibility attributes
        aniseed_toolkit.rigging.ikfk.create_ikfk_visibility(
            f"{self.config_control.ctl}.ikfk",
            ik_controls=self.ik_controls,
            fk_controls=self.fk_controls,
        )

        # -- Set up the space switches on the fk controls
        if self.option("Apply World Fk Switches").get():
            aniseed_toolkit.rig.space.setup_fk_worldspace_switches(self.fk_controls, config=self.config)

        self.nk_joints = ikfk_setup.blend_chain.names()
        self._create_snap()
        self._set_outputs()

    def _create_controls(self):
        """
        Here we create all the controls for the limb
        """
        # -- Add the configuration control
        self.config_control = aniseed_toolkit.rig.control.create(
            description=f"{self.prefix}Config",
            location=self.location,
            parent=self.org,
            shape="core_floating_config",
            config=self.config,
            match_to=self.joints[0],
            shape_scale=20.0,
            rotate_shape=self.shape_rotation,
        )

        # -- Create the fk controls, each one parented under the last
        fk_parent = self.org
        fk_controls = []
        for label, joint in zip(["UpperFK", "LowerFK", "FK"], self.joints[:3]):
            fk_control = aniseed_toolkit.rig.control.create(
                description=f"{self.prefix}{label}",
                location=self.location,
                parent=fk_parent,
                shape="core_paddle",
                config=self.config,
                match_to=joint,
                shape_scale=20.0,
                rotate_shape=self.shape_rotation,
            )
            fk_controls.append(fk_control)
            fk_parent = fk_control.ctl

        self.fk_upper_control, self.fk_lower_control, self.fk_end_control = fk_controls
        self.fk_controls = [fk_control.ctl for fk_control in fk_controls]

        # -- Now create the main IK control
        self.ik_target_control = aniseed_toolkit.rig.control.create(
            description=f"{self.prefix}IK",
            location=self.location,
            parent=self.org,
            shape="core_stumpy_cross",
            config=self.config,
            match_to=self.option("IK Control Transform").get() or self.joints[-1],
            shape_scale=20.0,
            rotate_shape=[-90, 0, 0],
        )
        self.ik_controls.append(self.ik_target_control.ctl)

        if self.option("Align IK To World").get():
            mref.get(self.ik_target_control.org).set_rotation([0, 0, 0], space="world")

        # -- Create the upvector control
        self.upvector_control = aniseed_toolkit.rig.control.create(
            description=f"{self.prefix}Upvector",
            location=self.location,
            parent=self.org,
            shape="core_sphere",
            config=self.config,
            match_to=self.joints[0],
            shape_scale=5.0,
            rotate_shape=None,
        )
        self.ik_controls.append(self.upvector_control.ctl)

        upvector_org = mref.get(self.upvector_control.org)
        upvector_org.set_position(
            aniseed_toolkit.core.maths.calculate_upvector_position(
                point_a=self.joints[0],
                point_b=self.joints[1],
                point_c=self.joints[2],
                length=1,
            ),
            space="world",
        )
        if self.option("Align Upvector To World").get():
            upvector_org.set_rotation([0, 0, 0], space="world")

    def _create_snap(self):
        """
        Creates the ik/fk snap groups: the ik target and upvector controls snap
        to the nk joints in the ik groups, and each fk control snaps to its nk
        joint in the fk groups.
        """
        ikfk_group, ikonly_group, fkonly_group = aniseed_toolkit.rigging.ikfk.create_snap_groups(
            label="Limb",
            prefix=self.prefix,
            location=self.location,
            ikfk_attribute=f"{self.config_control.ctl}.ikfk",
        )

        snappy.new(
            node=self.ik_target_control.ctl,
            target=self.nk_joints[2],
            group=[ikfk_group, ikonly_group],
        )

        snappy.new(
            node=self.upvector_control.ctl,
            target=self.nk_joints[1],
            group=[ikfk_group, ikonly_group],
        )

        snappy.add_empty_members(
            nodes=self.fk_controls,
            group=ikonly_group,
        )

        for fk_control, nk_joint in zip(self.fk_controls, self.nk_joints):
            snappy.new(
                node=fk_control,
                target=nk_joint,
                group=[ikfk_group, fkonly_group],
            )

        snappy.add_empty_members(
            nodes=self.ik_controls,
            group=fkonly_group,
        )

    def _set_outputs(self):
        """
        Sets the Blended Upper, Lower and Tip outputs to the first three nk
        (blend chain) joints.
        """

        self.output("Blended Upper").set(self.nk_joints[0])
        self.output("Blended Lower").set(self.nk_joints[1])
        self.output("Blended Tip").set(self.nk_joints[2])

    def _mirror_chain(self) -> list:
        """
        Returns the joints from the root joint to the tip joint, or an empty
        list if either is missing or the tip is not below the root.
        """
        root_joint = self.input("Root Joint").get()
        tip_joint = self.input("Tip Joint").get()

        if not root_joint or not tip_joint:
            return []

        if not mref.objExists(root_joint) or not mref.objExists(tip_joint):
            return []

        try:
            return aniseed_toolkit.scene.joints.get_between(
                start=root_joint,
                end=tip_joint,
            )

        except ValueError:
            return []

    def mirror_mixin_items_to_mirror(self) -> list:
        """
        Returns the chain from the root joint to the tip joint.
        """
        return self._mirror_chain()

    def mirror_mixin_parent_item(self) -> str:
        """
        Returns the parent of the root joint. Empty if there is no root joint
        or it has no parent.
        """
        root_joint = self.input("Root Joint").get()
        if not root_joint or not mref.objExists(root_joint):
            return ""

        parent = mref.get(root_joint).parent()
        return parent.name() if parent else ""

    def mirror_mixin_prepare(self, mirrored_from) -> None:
        """
        Uses the other side's chain if it already exists (the search and
        replaced names), otherwise copies the original chain (only the joints
        from the root to the tip) into the mirrored hierarchy for this component
        to drive.

        The "IK Control Transform" option is left to the search and replace,
        with a warning if it does not give an other side node.
        """
        ik_transform = self.option("IK Control Transform").get()
        if ik_transform:
            if not mref.objExists(ik_transform):
                print(
                    f"Mirror : {self.label()} IK Control Transform {ik_transform} "
                    f"does not exist"
                )
            elif ik_transform == mirrored_from.option("IK Control Transform").get():
                print(
                    f"Mirror : {self.label()} IK Control Transform {ik_transform} "
                    f"is the same node as the original's"
                )

        original_chain = mirrored_from._mirror_chain()
        if not original_chain:
            return

        if self.mirror_mixin_counterparts_exist(original_chain, self._mirror_chain()):
            return

        copies = self.mirror_mixin_copy_nodes(original_chain)
        self.input("Root Joint").set(copies[0])
        self.input("Tip Joint").set(copies[-1])
