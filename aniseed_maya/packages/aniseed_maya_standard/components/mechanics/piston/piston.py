"""
Provides the "Mechanics : Piston" component, a two control piston rig between
a base joint and a tip joint. Each end has an aim transform aimed at the
opposite control, sharing an upvector offset along a chosen axis, and the
joints are constrained to those aim transforms.
"""
import mref
import aniseed
import aniseed_toolkit
from aniseed_maya_standard.mixins import MirrorMixin


class PistonComponent(aniseed.RigComponent, MirrorMixin):
    """
    Builds a two-control piston rig between a Base joint and a Tip
    joint. A control is placed at each end (under its own parent in
    the control hierarchy) and the two ends aim at each other via
    ``aimConstraint``\\s stabilised by a shared upvector node offset
    from the root control. The Base and Tip joints are then
    parent-constrained to the aim transforms so the joints follow the
    aimed orientation as the controls move.
    """

    identifier = "Mechanics : Piston"

    def __init__(self, *args, **kwargs):
        """
        Declares the base/tip parent and joint inputs, the naming and upvector
        axis options and the Root and Tip aim transform outputs.
        """
        super().__init__(*args, **kwargs)

        self.declare_input(
            name="Base Parent",
            description="The node the root piston control will be parented under",
            value="",
            group="Control Rig"
        )

        self.declare_input(
            name="Tip Parent",
            description="The node the tip piston control will be parented under",
            value="",
            group="Control Rig"
        )

        self.declare_input(
            name="Base Joint",
            description="The joint at the root end of the piston. Driven by the root aim transform.",
            value="",
            group="Joint Requirements",
        )

        self.declare_input(
            name="Tip Joint",
            description="The joint at the tip end of the piston. Driven by the tip aim transform.",
            value="",
            group="Joint Requirements",
        )

        self.declare_option(
            name="Descriptive Prefix",
            description="Prefix used when naming the controls and helper transforms generated by the piston",
            value="",
            group="Naming",
        )

        self.declare_option(
            name="Upvector Axis",
            description=(
                "Axis along which the shared upvector node is offset "
                "from the root control. Used by both aim constraints to "
                "stabilise the piston's roll."
            ),
            value="X",
            group="Behaviour",
        )

        self.declare_option(
            name="Location",
            description="Location token (e.g. md/lf/rt) applied to generated node names",
            value=self.config.middle,
            group="Naming",
            should_inherit=True,
            pre_expose=True,
        )

        self.declare_output(
            name="Root",
            description="The aim transform driving the root joint. Follows the root control, aimed at the tip control.",
        )
        self.declare_output(
            name="Tip",
            description="The aim transform driving the tip joint. Follows the tip control, aimed at the root control.",
        )

    def input_widget(self, requirement_name: str):
        """
        Returns an object selector for the base/tip parent and joint inputs.
        """

        object_requirements = [
            "Base Parent",
            "Tip Parent",
            "Base Joint",
            "Tip Joint",
        ]

        if requirement_name in object_requirements:
            return aniseed.widgets.ObjectSelector(component=self)

    def option_widget(self, option_name: str):
        """
        Returns a location selector for Location and an axis selector for
        Upvector Axis.
        """
        if option_name == "Location":
            return aniseed.widgets.LocationSelector(self.config)

        if option_name == "Upvector Axis":
            return aniseed.widgets.AxisSelector()

    def on_enter_stack(self):
        """
        Hooks the Base Parent input to the parent component's default output.
        """
        # -- Attempt to auto resolve the parent based on its default output
        self.input("Base Parent").hook_to_parent()

    def run(self) -> bool:
        """
        Creates root and tip controls under their respective parents, each
        with an aim transform aimed at the opposite control (sharing an
        upvector offset 10cm along the Upvector Axis from the root control),
        parent constrains the base and tip joints to the aim transforms and
        sets them as the Root and Tip outputs.
        """

        piston_root_jnt = self.input("Base Joint").get()
        piston_tip_jnt = self.input("Tip Joint").get()

        prefix = self.option("Descriptive Prefix").get()
        location = self.option("Location").get()

        piston_root_ctl = aniseed_toolkit.rig.control.create(
            description=f"{prefix}PistonRoot",
            location=location,
            config=self.config,
            parent=self.input("Base Parent").get(),
            shape="core_cube",
            match_to=piston_root_jnt,
        )

        piston_tip_ctl = aniseed_toolkit.rig.control.create(
            description=f"{prefix}PistonTip",
            location=location,
            config=self.config,
            parent=self.input("Tip Parent").get(),
            shape="core_cube",
            match_to=piston_tip_jnt,
        )

        aim_root = aniseed_toolkit.scene.transforms.create(
            classification="piv",
            description=f"{prefix}PistonRootAim",
            location=location,
            config=self.config,
            parent=piston_root_ctl.ctl,
            match_to=piston_root_ctl.ctl,
        )

        aim_tip = aniseed_toolkit.scene.transforms.create(
            classification="piv",
            description=f"{prefix}PistonTipAim",
            location=location,
            config=self.config,
            parent=piston_tip_ctl.ctl,
            match_to=piston_tip_ctl.ctl,
        )

        upvector = mref.get(
            aniseed_toolkit.scene.transforms.create(
                classification="upv",
                description=f"{prefix}PistonUpVector",
                location=location,
                config=self.config,
                parent=piston_root_ctl.ctl,
                match_to=piston_root_ctl.ctl,
            ),
        )

        upvector_axis = self.option("Upvector Axis").get().upper()
        upvector.attr(f"translate{upvector_axis}").set(10)

        # -- Each end aims at the opposite control, sharing the upvector
        aim_pairs = [
            (piston_tip_ctl.ctl, aim_root),
            (piston_root_ctl.ctl, aim_tip),
        ]
        for aim_target, aim_node in aim_pairs:
            mref.aimConstraint(
                aim_target,
                aim_node,
                aimVector=[0, 1, 0],
                upVector=[1, 0, 0],
                worldUpType="object",
                worldUpObject=upvector,
                maintainOffset=False,
            )

        mref.parentConstraint(
            aim_root,
            piston_root_jnt,
            maintainOffset=True,
        )

        mref.parentConstraint(
            aim_tip,
            piston_tip_jnt,
            maintainOffset=True,
        )

        self.output("Root").set(aim_root)
        self.output("Tip").set(aim_tip)

        return True

    def mirror_mixin_items_to_mirror(self) -> list:
        """
        Returns the base and tip joints. Empty unless both are set, so that
        the mirrored component's items always pair up by position.
        """
        base_joint = self.input("Base Joint").get()
        tip_joint = self.input("Tip Joint").get()

        if not base_joint or not tip_joint:
            return []

        return [base_joint, tip_joint]

    def mirror_mixin_parent_item(self) -> str:
        """
        Returns the parent of the base joint. Empty if there is no base joint
        or it has no parent.
        """
        base_joint = self.input("Base Joint").get()
        if not base_joint or not mref.objExists(base_joint):
            return ""

        parent = mref.get(base_joint).parent()
        return parent.name() if parent else ""

    def mirror_mixin_prepare(self, mirrored_from) -> None:
        """
        Uses the other side's base and tip joints if they already exist (the
        search and replaced names), otherwise copies the original joints into
        the mirrored hierarchy for this component to drive. The tip copy goes under
        the base copy if the tip is a child of the base.
        """
        original_joints = [
            mirrored_from.input("Base Joint").get(),
            mirrored_from.input("Tip Joint").get(),
        ]
        mirrored_joints = [
            self.input("Base Joint").get(),
            self.input("Tip Joint").get(),
        ]

        if not all(original_joints):
            return

        if self.mirror_mixin_counterparts_exist(original_joints, mirrored_joints):
            return

        base_copy, tip_copy = self.mirror_mixin_copy_nodes(original_joints)
        self.input("Base Joint").set(base_copy)
        self.input("Tip Joint").set(tip_copy)
